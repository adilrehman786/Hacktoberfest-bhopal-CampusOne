// Dates are generated relative to "today" so the demo always has
// upcoming events and urgent deadlines, whatever day it is run.

function isoOffset(days) {
  const d = new Date();
  d.setHours(12, 0, 0, 0);
  d.setDate(d.getDate() + days);
  return d.toISOString().slice(0, 10);
}

