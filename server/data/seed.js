export function generateSeed() {
  return raw.map((e, i) => {
    const [eventDay, deadlineDay, postedAgo] = e.when;
    const { when, ...rest } = e;
    return {
      id: `evt-${String(i + 1).padStart(3, '0')}`,
      ...rest,
      date: isoOffset(eventDay),
      registrationDeadline: deadlineDay === null ? null : isoOffset(deadlineDay),
      postedAt: isoOffset(-postedAgo),
      registrationLink: `https://campusone.app/register/evt-${String(i + 1).padStart(3, '0')}`,
      source: 'seed',
    };
  });
}
